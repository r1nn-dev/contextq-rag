"""ai 스키마 마이그레이션 up·down과 제약 검증 (실제 PostgreSQL)."""

import pytest
from sqlalchemy import Engine, inspect, text
from sqlalchemy.exc import IntegrityError

from tests.integration.conftest import alembic_run

pytestmark = pytest.mark.integration

TABLES = {"sources", "compare_pairs", "ingest_runs", "index_pointers"}


def _ai_tables(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names(schema="ai")) - {"alembic_version"}


def test_upgrade_creates_tables_and_downgrade_removes_them(migrated: Engine) -> None:
    assert _ai_tables(migrated) == TABLES

    alembic_run(migrated, "downgrade", "base")
    assert _ai_tables(migrated) == set()

    alembic_run(migrated, "upgrade", "head")
    assert _ai_tables(migrated) == TABLES


def test_models_match_migrations(migrated: Engine) -> None:
    # SQLAlchemy 모델과 리비전 결과가 다르면 alembic check가 예외를 낸다
    alembic_run(migrated, "check")


def test_seed_catalog(migrated: Engine) -> None:
    with migrated.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT source_key, framework, version_label, repo_url, ref, doc_path,"
                " doc_format, adapter_class, enabled FROM ai.sources ORDER BY source_key"
            )
        ).all()
        pairs = conn.execute(text("SELECT source_key_a, source_key_b FROM ai.compare_pairs")).all()

    assert [tuple(r) for r in rows] == [
        (
            "langchain_v03",
            "langchain",
            "v0.3",
            "langchain-ai/langchain",
            "v0.3",
            "docs/docs/",
            "DOCUSAURUS",
            "DocusaurusAdapter",
            True,
        ),
        (
            "langchain_v1x",
            "langchain",
            "v1.x",
            "langchain-ai/docs",
            "main",
            "src/oss/",
            "MINTLIFY",
            "MintlifyAdapter",
            True,
        ),
    ]
    assert [tuple(p) for p in pairs] == [("langchain_v03", "langchain_v1x")]


def test_seed_downgrade_removes_rows(migrated: Engine) -> None:
    alembic_run(migrated, "downgrade", "0001")
    with migrated.connect() as conn:
        assert conn.execute(text("SELECT count(*) FROM ai.sources")).scalar_one() == 0


_INSERT_SOURCE = (
    "INSERT INTO ai.sources (source_key, framework, version_label, display_name, repo_url,"
    " ref, doc_path, doc_format, adapter_class, enabled, created_at, updated_at)"
    " VALUES (:key, 'langchain', :ver, 'x', 'r', 'main', 'd/', 'MINTLIFY', 'A', true, now(), now())"
)


@pytest.mark.parametrize(
    ("key", "ver"),
    [("langchain_v03", "v9"), ("other_key", "v0.3")],
    ids=["uq_sources_key", "uq_sources_fw_ver"],
)
def test_source_unique_constraints(migrated: Engine, key: str, ver: str) -> None:
    with pytest.raises(IntegrityError), migrated.begin() as conn:
        conn.execute(text(_INSERT_SOURCE), {"key": key, "ver": ver})


def test_compare_pair_requires_known_source(migrated: Engine) -> None:
    with pytest.raises(IntegrityError), migrated.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO ai.compare_pairs (source_key_a, source_key_b, created_at)"
                " VALUES ('langchain_v03', 'unknown_key', now())"
            )
        )


def test_ingest_run_accepts_explicit_id_for_snapshot_restore(migrated: Engine) -> None:
    # 스냅샷 복원 시 manifest의 run id를 그대로 넣는다 (GENERATED BY DEFAULT)
    with migrated.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO ai.ingest_runs (id, source_key, status, accept_drift, created_at,"
                " updated_at) VALUES (42, 'langchain_v03', 'RESTORING', false, now(), now())"
            )
        )
        assert conn.execute(text("SELECT id FROM ai.ingest_runs")).scalar_one() == 42


def test_index_pointer_requires_existing_run(migrated: Engine) -> None:
    with pytest.raises(IntegrityError), migrated.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO ai.index_pointers (source_key, active_run_id, created_at, updated_at)"
                " VALUES ('langchain_v03', 999, now(), now())"
            )
        )
