"""ai 스키마 테이블 정의가 db-design §3.9~3.12·§4와 같은지 DDL 컴파일로 확인한다 (DB 불필요)."""

import pytest
from sqlalchemy import Identity, Table
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from src.domain.tables import AI_SCHEMA, Base


def _ddl(table: Table) -> str:
    return str(CreateTable(table).compile(dialect=postgresql.dialect()))


def _table(name: str) -> Table:
    return Base.metadata.tables[f"{AI_SCHEMA}.{name}"]


def test_four_tables_in_ai_schema() -> None:
    assert set(Base.metadata.tables) == {
        "ai.sources",
        "ai.compare_pairs",
        "ai.ingest_runs",
        "ai.index_pointers",
    }


@pytest.mark.parametrize(
    ("table", "expected"),
    [
        (
            "sources",
            [
                "id BIGINT GENERATED ALWAYS AS IDENTITY",
                "CONSTRAINT pk_sources PRIMARY KEY (id)",
                "CONSTRAINT uq_sources_key UNIQUE (source_key)",
                "CONSTRAINT uq_sources_fw_ver UNIQUE (framework, version_label)",
                "enabled BOOLEAN NOT NULL",
            ],
        ),
        (
            "compare_pairs",
            [
                "CONSTRAINT uq_cp_pair UNIQUE (source_key_a, source_key_b)",
                "CONSTRAINT fk_cp_source_a FOREIGN KEY(source_key_a) "
                "REFERENCES ai.sources (source_key)",
                "CONSTRAINT fk_cp_source_b FOREIGN KEY(source_key_b) "
                "REFERENCES ai.sources (source_key)",
            ],
        ),
        (
            "ingest_runs",
            [
                # 스냅샷 복원 시 명시적 ID INSERT 허용 (db-design §3.11)
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY",
                "commit_sha CHAR(40)",
                "chunk_params JSONB",
                "chunk_params_hash VARCHAR(8)",
                "accept_drift BOOLEAN NOT NULL",
                "validation_report JSONB",
                "embedding_cost_usd NUMERIC(8, 6)",
            ],
        ),
        (
            "index_pointers",
            [
                "source_key VARCHAR(50) NOT NULL",
                "CONSTRAINT pk_index_pointers PRIMARY KEY (source_key)",
                "CONSTRAINT fk_ip_run FOREIGN KEY(active_run_id) REFERENCES ai.ingest_runs (id)",
            ],
        ),
    ],
)
def test_columns_and_constraints_match_db_design(table: str, expected: list[str]) -> None:
    ddl = _ddl(_table(table))
    for fragment in expected:
        assert fragment in ddl


def test_ingest_runs_indexes() -> None:
    indexes = {
        str(CreateIndex(i).compile(dialect=postgresql.dialect()))
        for i in _table("ingest_runs").indexes
    }
    assert indexes == {
        "CREATE INDEX idx_ir_source_status ON ai.ingest_runs (source_key, status)",
        "CREATE INDEX idx_ir_source_created ON ai.ingest_runs (source_key, created_at DESC)",
    }


@pytest.mark.parametrize("table", sorted(Base.metadata.tables.values(), key=lambda t: t.name))
def test_no_db_default_and_no_cascade(table: Table) -> None:
    # 기본값은 애플리케이션에서 지정, ON DELETE CASCADE 전면 금지 (db-design §4)
    ddl = _ddl(table)
    assert " DEFAULT " not in ddl.replace("GENERATED BY DEFAULT", "")
    assert "CASCADE" not in ddl
    for column in table.columns:
        # 예외: PostgreSQL IDENTITY 시퀀스
        assert column.server_default is None or isinstance(column.server_default, Identity)


def test_immutable_compare_pairs_has_no_updated_at() -> None:
    assert "updated_at" not in _table("compare_pairs").columns
